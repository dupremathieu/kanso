const pattern = /\{(\w+)\}/g;

export function translate(messages, key, vars) {
  const template = Object.prototype.hasOwnProperty.call(messages, key)
    ? messages[key]
    : key;
  if (!vars) return template;
  return template.replace(pattern, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

export function createTranslator(dictionary) {
  return (key, vars) => translate(dictionary, key, vars);
}

export const t = createTranslator(messages);
